assert.throws(() => act(protectedPlan, { type: 'move', id: 'c1:0', date: '2026-11-06' }, protectedContext), /Completed/);
assert.throws(() => act(protectedPlan, { type: 'move', id: recordedRun.id, date: '2026-11-06' }, protectedContext), /Completed/);
