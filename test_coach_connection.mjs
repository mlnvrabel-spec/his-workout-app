import assert from 'node:assert/strict';
import { CoachConnection, coachBase } from './src/core/CoachConnection.js';
const page = { origin: 'https://dashboard.example', hostname: 'dashboard.example' };
globalThis.window = { location: page };
const saved = new Map();
globalThis.localStorage = { getItem: key => saved.get(key), setItem: (key, value) => saved.set(key, value) };
assert.throws(() => coachBase('http://backend.example', page), /HTTPS/);
assert.throws(() => coachBase('https://key@backend.example', page), /credentials/);
assert.throws(() => coachBase('https://backend.example/?key=secret', page), /credentials/);
assert.throws(() => coachBase('http://localhost:8001', page), /HTTPS/);
assert.equal(coachBase('http://localhost:8001', { hostname: 'localhost' }), 'http://localhost:8001');
const calls = [];
globalThis.fetch = async (url, options) => {
    calls.push({ url, ...options });
    return { ok: true, json: async () => ({ connected: options.method !== 'DELETE', provider: 'deepseek' }) };
};
const connection = new CoachConnection();
await connection.connect('https://backend.example', 'deepseek', 'test-code', 'test-key');
assert.equal(connection.connected, true);
assert.deepEqual([...saved], [['coach_backend_url', 'https://backend.example']]);
assert.equal(calls[0].credentials, 'include');
assert.equal(calls[0].cache, 'no-store');
assert.equal(calls[0].redirect, 'error');
assert.equal(JSON.parse(calls[0].body).api_key, 'test-key');
assert.equal(JSON.stringify(connection).includes('test-key'), false);
await connection.disconnect();
assert.equal(connection.connected, false);
globalThis.fetch = async () => ({ ok: true, json: async () => { throw new Error('HTML'); } });
await assert.rejects(connection.status(), /Hosting setup/);
console.log('Coach HTTPS validation, session transport, secret persistence and unavailable backend: OK');

const { ChatAssistant } = await import('./src/core/ChatAssistant.js');
const coach = Object.create(ChatAssistant.prototype);
const exercise = { name: 'Cable Fly', _exerciseId: 'fly', rir: '0-1', reps: '10-15' };
coach.engine = { protocolData: [{ title: 'Push A', exercises: [exercise] }, { title: 'Pull A', exercises: [] }], state: { day: 0, activeDay: 0 }, getPreviousLog: () => ({ sets: [{ weight_kg: 20, reps: 12 }] }), _nextDay: () => 1 };
coach.history = []; coach.currentReadiness = 50; coach.hasReadiness = false;
coach.input = { value: 'How do I set my elbows for Cable Fly?' }; coach.sendBtn = {}; coach.addMsg = () => {};
const sent = [];
coach.connection = { request: async (_, options) => { sent.push(options.body); return { cue: 'Keep a soft elbow bend.', source: 'provider' }; } };
await coach.send();
coach.input.value = 'Should that stay constant?'; await coach.send();
assert.equal(sent[0].exercise_name, 'Cable Fly');
assert.equal(sent[0].last_session_log, '20 kg × 12 · Effort unreported');
assert.equal(sent[0].readiness_available, false);
assert.deepEqual(sent[1].history.map(turn => turn.role), ['user', 'assistant']);
assert.equal(sent[1].history[0].content, 'How do I set my elbows for Cable Fly?');
coach.engine.getPreviousLog = () => ({ sets: [{ weight_kg: 20, reps: 12, rpe: 9 }] });
await coach.generateCoachingCue('fly', 'Cable Fly', { targetRir: '0-1', repRange: '10-15' });
assert.equal(sent.at(-1).last_session_log, '20 kg × 12 · RPE 9 · unverified');
coach.engine.getPreviousLog = () => ({ sets: [{ weight_kg: 20, reps: 12, rpe: null, rpe_source: 'unreported' }] });
await coach.generateCoachingCue('fly', 'Cable Fly', { targetRir: '0-1', repRange: '10-15' });
assert.equal(sent.at(-1).last_session_log, '20 kg × 12 · Effort unreported');
coach.connection.request = async () => { throw new Error('offline'); };
coach.input.value = 'What about my elbow?'; await coach.send();
assert.equal(coach.sending, false); assert.equal(coach.sendBtn.disabled, false);
console.log('Chat exercise context, prior sets, follow-up history and offline send recovery: OK');
